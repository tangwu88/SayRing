const locale = process.argv[2];
if (!['en','zh-TW','de','fr','es','ja','ko'].includes(locale)) throw Error('Choose an allowed draft locale');
const output = [];
for (let start = 0; start < labels.length; start += 30) {
  const group = labels.slice(start, start + 30);
  const url = new URL('https://translate.googleapis.com/translate_a/single');
  for (const [key,value] of Object.entries({client:'gtx',sl:'en',tl:locale,dt:'t',q:group.join('\n')})) url.searchParams.set(key,value);
  const response = await fetch(url, { signal: AbortSignal.timeout(20000) });
  if (!response.ok) throw Error('Draft translation unavailable: '+response.status);
  const data = await response.json();
  const translated = data[0].map(item=>item[0]).join('').split('\n');
  if (translated.length !== group.length) throw Error('Draft row count mismatch; no partial catalog produced');
  output.push(...translated.map(text=>text.trim()));
}
process.stdout.write(JSON.stringify(output));
